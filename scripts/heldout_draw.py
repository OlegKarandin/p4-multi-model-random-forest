"""The frozen held-out batch (plan Phase 4, audit C6): draw ~30 never-compiled
campaign designs, predict them with the CURRENT model, write that down, THEN
compile them with the real p4c and score once.

WHY THIS EXISTS. Every accuracy figure the resource model carries was measured
on archives its own authors had already looked at (compiler_calibration_v6,
_extra, tcam_margin_screen, the pinned re-compiles of all three). This script
is the honest check: a seeded draw of designs nobody has compiled, whose
predictions are fixed on disk before p4c ever sees them. The rule that goes
with it: whatever the score, the model is NOT tuned in response. A miss is
logged and reported, never fitted away.

THREE STEPS, one CLI flag each, run in this order:

  --draw     Seeded draw from results/campaign_backup_20260825. Every design
             is refit from its archived best_params (scripts.replay_alignment
             .refit_pair) and, on the aligned joint arms (joint-d*), aligned
             with the CURRENT threshold alignment (align_with_policy) -- the
             Phase 3b code this batch is meant to be generated by. joint-off
             and independent are never aligned, exactly as in the campaign.
             The pair is priced by multi_model_memory_evaluation, the P4
             program is generated (the generator always emits the C5
             @placement_priority / @pa_no_overlay pragmas) and replayed end
             to end (p4_artifact_replay.replay_design) as a second,
             program-level prediction. manifest.json -- seed, git commit,
             every drawn id, every prediction, and a sha256 of every
             generated program -- is written, and the step REFUSES to run
             again over an existing manifest.
  --compile  Compiles the manifest's designs ONE AT A TIME (RAM: one p4c at a
             time, never two), each only after checking its program still
             hashes to the manifest's sha256. Resumable: a design with a
             finished compile directory and a row in compiled.csv is skipped.
  --score    Design level (stage_depth vs p4c's stages_real, blocks vs
             tcam_real) and per table (tcam_table_scoreboard.price_in_stage,
             the packer's own in-stage pricing, conditioned on the placement
             p4c actually committed). Writes design_scores.csv /
             table_scores.csv next to the manifest.

THE DRAW (draw_designs), in full:
  1. Candidates: every backup row, minus every design ALREADY COMPILED
     anywhere under results/ (compiled_identities: the (arm_slug, M, k,
     split) of every campaign-derived compile, from the calibration CSVs and
     the margin_* compile directories), minus every row whose CONTENT
     (encoding family, split, both feature lists, best_params) matches a
     compiled row's -- such a row would regenerate the same forests. Then
     content-duplicates among the candidates are collapsed to one.
  2. Candidates are sorted by (arm_slug, M, k, split) and permuted with
     numpy.random.default_rng(SEED).
  3. UNIFORM stratum: the first n_uniform rows of that order, whatever their
     prediction -- drawn before any prediction is looked at.
  4. Then the order is walked on: a row predicted at stage_depth 11-13 fills
     the DEPTH stratum while it has room; otherwise a row at 55-64 combined
     key bytes fills the BYTES stratum while it has room; otherwise it is
     passed over. The walk stops when both are full.
  "Combined key bytes" = the crossbar bytes of the design's DISTINCT
  classification keys summed: B_app + B_ddos under disjoint (one term when
  the two keys are the same fields), the one shared key's B under joint.
  N=30 splits 15 depth / 10 bytes / 5 uniform (split_counts).

Run (from the repository root), in order:
  "C:/Users/olegk/miniconda3/envs/PolimiML/python.exe" scripts/heldout_draw.py --draw
  "C:/Users/olegk/miniconda3/envs/PolimiML/python.exe" scripts/heldout_draw.py --compile
  "C:/Users/olegk/miniconda3/envs/PolimiML/python.exe" scripts/heldout_draw.py --score
"""
